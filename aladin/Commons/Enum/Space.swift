import Foundation

enum Space: CGFloat {

    /// Extra small spacing (4pt)
    case xxSmall = 4.0

    /// Extra small spacing (8pt)
    case xSmall = 8.0

    /// Small spacing (16pt)
    case small = 16.0

    /// Medium spacing (24pt)
    case medium = 24.0

    /// Large spacing (32pt)
    case large = 32.0

    /// Extra large spacing (40pt)
    case xLarge = 40.0

    /// 2x Extra large spacing (48pt)
    case xxLarge = 48.0

    /// 3x Extra large spacing (56pt)
    case xxxLarge = 56.0

    /// 4x Extra large spacing (64pt)
    case huge = 64.0

    /// 5x Extra large spacing (72pt)
    case xHuge = 72.0

    /// 6x Extra large spacing (80pt)
    case xxHuge = 80.0

    /// 7x Extra large spacing (88pt)
    case xxxHuge = 88.0

    /// 8x Extra large spacing (96pt)
    case giant = 96.0

    /// 9x Extra large spacing (104pt)
    case xGiant = 104.0

    /// 10x Extra large spacing (112pt)
    case xxGiant = 112.0

    /// 11x Extra large spacing (120pt)
    case xxxGiant = 120.0

    /// 12x Extra large spacing (128pt)
    case xxxxGiant = 128.0
}
